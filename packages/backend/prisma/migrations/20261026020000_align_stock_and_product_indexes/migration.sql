-- 開発DBにだけ残っていた索引を、リポジトリの定義へ戻す（d798）。
--
-- stocks_product_id_idx は、予測在庫の一覧を品目から先に引く変更（d631・e780800）で
-- 移行 20261020163000 として入り、その変更の取り消し（d651・1daa87b）で移行ごと消えた。
-- 移行を消しても、適用済みの DB には索引が残る。リポジトリの定義から消えたことで、
-- 以後のどの環境でもこの索引が作られなくなっていた。
-- 品目だけの条件（product_id IN (...)）は、倉庫を先頭にした複合一意
-- (warehouse_id, product_id) では引けないため、この索引を戻す。
--
-- 本番の DB には旧名の移行（20261020163000）が適用済みとして残っているため、
-- migrate deploy はこの移行を「未適用」とみなして、またこの SQL を流す。
-- 本番では索引が既にあるので、同じ名前を作ろうとして失敗しないよう IF NOT EXISTS にする。
CREATE INDEX IF NOT EXISTS "stocks_product_id_idx" ON "stocks"("product_id");
