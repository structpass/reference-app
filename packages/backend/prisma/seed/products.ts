function generateProducts(
  categoryMap: Record<string, number>,
  rng: Rng,
): Array<{
  code: string;
  name: string;
  description: string;
  categoryId: number;
  price: number;
  purchasePrice: number;
  unit: string;
  stockQuantity: number;
}> {
  const generated: ReturnType<typeof generateProducts> = [];
  let idx = 51;

  for (const tpl of CATEGORY_TEMPLATES) {
    const categoryId = categoryMap[tpl.categoryName];
    for (let i = 0; i < tpl.count; i++) {
      const prefix = pickRandom(tpl.prefixes, rng);
      const suffix = pickRandom(tpl.suffixes, rng);
      const desc = pickRandom(tpl.descriptions, rng);
      const price = Math.round(randomInt(tpl.priceRange[0], tpl.priceRange[1], rng) / 100) * 100;
      const purchasePrice = Math.round(price * (0.6 + rng() * 0.1));
      const stockQuantity = randomInt(0, 300, rng);

      generated.push({
        code: `PRD-${padNum(idx, 4)}`,
        name: `${prefix} ${suffix}`,
        description: desc,
        categoryId,
        price,
        purchasePrice,
        unit: tpl.unit,
        stockQuantity,
      });
      idx++;
    }
  }
  return generated;
}

export async function seedProducts(
  prisma: PrismaClient,
  categoryMap: Record<string, number>,
  createdById: string,
  rng: Rng,
): Promise<Product[]> {
  // Upsert static 50
  for (const { categoryName, ...p } of STATIC_PRODUCTS) {
    await prisma.product.upsert({
      where: { code: p.code },
      update: {},
      create: {
        ...p,
        categoryId: categoryMap[categoryName],
        status: p.code === 'PRD-005' ? 'INACTIVE' : 'ACTIVE',
        createdBy: createdById,
      },
    });
  }

  // Generate 950 more
  const generated = generateProducts(categoryMap, rng);
  const BATCH = 100;
  for (let i = 0; i < generated.length; i += BATCH) {
    const batch = generated.slice(i, i + BATCH);
    await prisma.product.createMany({
      data: batch.map((p) => ({
        ...p,
        status: 'ACTIVE' as const,
        createdBy: createdById,
      })),
      skipDuplicates: true,
    });
  }

  const products = await prisma.product.findMany({ orderBy: { code: 'asc' } });
  console.log('Products created:', products.length);
  return products;
}
